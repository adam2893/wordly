#!/usr/bin/env python3
"""Fetch and build Sudoku puzzle banks from TN1ck/super-sudoku.

Output:
  public/words-sudoku.js
    SUDOKU_EPOCH    date of puzzle #1
    SUDOKU_PUZZLES  { easy: [...], medium: [...], hard: [...] }
                    where each entry is [givens_81, solution_81]

Existing puzzles are kept in order; pass --rebuild to start fresh.
"""

import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE_DIR = os.path.join(ROOT, "tools", ".cache", "sudoku")
OUT = os.path.join(ROOT, "public", "words-sudoku.js")

EPOCH = "2026-11-02"
TARGET = int(os.environ.get("SUDOKU_TARGET", 400))

BASE_URL = "https://raw.githubusercontent.com/TN1ck/super-sudoku/master/sudokus"
DIFFICULTIES = ["easy", "medium", "hard"]


def fetch_lines(diff):
    os.makedirs(CACHE_DIR, exist_ok=True)
    path = os.path.join(CACHE_DIR, f"{diff}.txt")
    if not os.path.exists(path):
        url = f"{BASE_URL}/{diff}.txt"
        req = urllib.request.Request(url, headers={"User-Agent": "WordlySudokuBuilder/1.0"})
        with urllib.request.urlopen(req, timeout=20) as resp:
            text = resp.read().decode("utf-8")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    with open(path, "r", encoding="utf-8") as fh:
        return [line.strip() for line in fh if len(line.strip()) == 81 and line.strip().isdigit()]


def solve_sudoku(givens_str):
    """Fast bitmask MRV backtracking solver (ported from TN1ck/super-sudoku)."""
    board = [int(c) for c in givens_str]
    row_mask = [0] * 9
    col_mask = [0] * 9
    box_mask = [0] * 9
    empties = []

    for idx, val in enumerate(board):
        if val == 0:
            empties.append(idx)
            continue
        r, c = divmod(idx, 9)
        b = (r // 3) * 3 + (c // 3)
        bit = 1 << val
        if (row_mask[r] & bit) or (col_mask[c] & bit) or (box_mask[b] & bit):
            return None
        row_mask[r] |= bit
        col_mask[c] |= bit
        box_mask[b] |= bit

    ALL_BITS = 0x3FE  # bits 1..9

    def backtrack(k):
        if k == len(empties):
            return True
        # Find empty slot with fewest candidates (MRV)
        best_i = k
        best_count = 10
        best_cand = 0
        for i in range(k, len(empties)):
            idx = empties[i]
            r, c = divmod(idx, 9)
            b = (r // 3) * 3 + (c // 3)
            cand = ALL_BITS & ~(row_mask[r] | col_mask[c] | box_mask[b])
            cnt = cand.bit_count()
            if cnt < best_count:
                best_count = cnt
                best_i = i
                best_cand = cand
                if cnt <= 1:
                    break
        if best_count == 0:
            return False

        empties[k], empties[best_i] = empties[best_i], empties[k]
        idx = empties[k]
        r, c = divmod(idx, 9)
        b = (r // 3) * 3 + (c // 3)

        cand = best_cand
        while cand:
            bit = cand & -cand
            cand ^= bit
            val = bit.bit_length() - 1
            board[idx] = val
            row_mask[r] |= bit
            col_mask[c] |= bit
            box_mask[b] |= bit
            if backtrack(k + 1):
                return True
            row_mask[r] ^= bit
            col_mask[c] ^= bit
            box_mask[b] ^= bit
            board[idx] = 0

        empties[k], empties[best_i] = empties[best_i], empties[k]
        return False

    if not backtrack(0):
        return None
    return "".join(str(x) for x in board)


def read_existing():
    if not os.path.exists(OUT):
        return {}
    with open(OUT, "r", encoding="utf-8") as fh:
        m = re.search(r"const SUDOKU_PUZZLES = (\{.*\});", fh.read(), re.S)
    return json.loads(m.group(1)) if m else {}


def main():
    rebuild = "--rebuild" in sys.argv
    existing = {} if rebuild else read_existing()
    out_bank = {}

    for diff in DIFFICULTIES:
        kept_list = list(existing.get(diff) or [])
        kept_count = len(kept_list)
        seen_givens = {pair[0] for pair in kept_list}
        raw_lines = fetch_lines(diff)
        for givens in raw_lines:
            if len(kept_list) >= TARGET:
                break
            if givens in seen_givens:
                continue
            sol = solve_sudoku(givens)
            if sol:
                kept_list.append([givens, sol])
                seen_givens.add(givens)
        out_bank[diff] = kept_list
        print(f"Sudoku ({diff}): kept {kept_count}, wrote {len(kept_list)} total")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_sudoku.py from TN1ck/super-sudoku - do not edit by hand.\n")
        fh.write(f'const SUDOKU_EPOCH = "{EPOCH}";\n')
        fh.write("const SUDOKU_PUZZLES = ")
        fh.write(json.dumps(out_bank, separators=(",", ":")))
        fh.write(";\n")


if __name__ == "__main__":
    main()
